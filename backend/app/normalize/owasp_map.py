def _index() -> dict[str, str]:
    found: dict[str, str] = {}
    duplicated: set[str] = set()
    for label, numbers in CATEGORIES.items():
        for number in numbers:
            cwe_id = f"CWE-{number}"
            if cwe_id in found:
                duplicated.add(cwe_id)
            else:
                found[cwe_id] = label
    for cwe_id in duplicated:
        found.pop(cwe_id, None)
    return found


# A CWE listed under two categories is omitted rather than guessed.
_BY_CWE = _index()


def owasp_for(cwe_id: str | None) -> str | None:
    if not cwe_id:
        return None
    return _BY_CWE.get(cwe_id)
